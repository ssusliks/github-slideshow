import { chromium, GL_ARGS } from './pw.mjs';
const base = process.argv[2] ?? 'http://localhost:5199/';
const browser = await chromium.launch({ args: GL_ARGS });
// exploratory helper (not part of the regression suite)
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true, locale: 'en-US' });
const page = await ctx.newPage();
page.on('console', (m) => { if (m.type() === 'error') console.log('[console]', m.text().slice(0, 300)); });
page.on('pageerror', (e) => console.log('[pageerror]', e.message, (e.stack ?? '').split('\n').slice(1, 4).join(' | ')));
await page.goto(base);
await page.waitForSelector('#btn-play');
await page.click('#btn-play');
await page.waitForSelector('#btn-start-level');
await page.screenshot({ path: 'e2e/out/01-level-dialog.png' });
await page.click('#btn-start-level');
await page.waitForFunction(() => !!window.__app.battle);
await page.waitForTimeout(1500);
await page.screenshot({ path: 'e2e/out/02-battle-tutorial.png' });
const slotPt = (i) => page.evaluate((i) => { const b = window.__app.battle; const s = b.b.slotPos(i); return b.view.screenOf(s.x, s.y, 0.05); }, i);
const drag = async (from, to) => { await page.mouse.move(from.x, from.y); await page.mouse.down(); await page.mouse.move((from.x + to.x) / 2, (from.y + to.y) / 2, { steps: 5 }); await page.mouse.move(to.x, to.y, { steps: 5 }); await page.waitForTimeout(150); return to; };
const card = await page.locator('.card[data-tower="archer"]').boundingBox();
const c = { x: card.x + card.width / 2, y: card.y + card.height / 2 };
const s0 = await slotPt(0);
await drag(c, s0);
await page.screenshot({ path: 'e2e/out/03-dragging.png' });
await page.mouse.up();
await page.waitForTimeout(400);
await drag(c, await slotPt(1)); await page.mouse.up();
await page.waitForTimeout(400);
console.log('towers after 2 drags:', await page.evaluate(() => window.__app.battle.b.s.towers.map((t) => [t.def, t.slot])));
await page.click('#btn-start', { force: true });
await page.waitForTimeout(9000);
await page.screenshot({ path: 'e2e/out/04-wave.png' });
console.log('state:', await page.evaluate(() => { const s = window.__app.battle.b.s; return { phase: s.phase, wave: s.wave, enemies: s.enemies.length, coins: s.coins, hp: s.castleHp, kills: s.stats.kills }; }));
await browser.close();
